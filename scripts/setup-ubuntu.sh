#!/usr/bin/env bash
# Prepares Ubuntu 24.04 or 26.04 to run OctopusBeak from source. Run it as
# yourself; it asks for sudo only for the steps that change the system:
#   1. apt packages Electron, Playwright's headless shell, and the keyring need;
#   2. the AppArmor profile of ADR 0138 for this checkout's Electron path.
# It does not install Node: use the version in .tool-versions (mise, nvm, asdf).
# Then run npm install and npm run doctor.
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
electron_path="$project_root/node_modules/electron/dist/electron"

# Keep in step with UBUNTU_APT_PACKAGES in scripts/ubuntu-environment.mjs.
packages=(
  libnss3 libnspr4 libatk1.0-0t64 libatk-bridge2.0-0t64 libcups2t64 libdrm2
  libgbm1 libgtk-3-0t64 libpango-1.0-0 libcairo2 libasound2t64 libxkbcommon0
  libxcomposite1 libxdamage1 libxfixes3 libxrandr2 libxss1 libxshmfence1
  libnotify4 xdg-utils libsecret-1-0 gnome-keyring
)

# shasum keeps --print-profile working on macOS, where the repository's checks also run.
sha256() { if command -v sha256sum > /dev/null; then sha256sum; else shasum -a 256; fi; }
profile_name="octopusbeak-dev-$(printf '%s' "$electron_path" | sha256 | cut -c1-12)"

print_profile() {
  cat <<EOF
# Generated by OctopusBeak (ADR 0138). Lets Electron use its user-namespace sandbox.
abi <abi/4.0>,
include <tunables/global>

profile $profile_name "$electron_path" flags=(unconfined) {
  userns,

  include if exists <local/$profile_name>
}
EOF
}

case "${1:-}" in
  --print-packages) printf '%s\n' "${packages[@]}"; exit 0 ;;
  --print-profile) print_profile; exit 0 ;;
  "") ;;
  *) echo "Usage: $0 [--print-packages | --print-profile]" >&2; exit 2 ;;
esac

if [[ "$(id -u)" -eq 0 ]]; then
  echo "Run this script as yourself, not with sudo; it calls sudo where it must." >&2
  exit 1
fi

. /etc/os-release
if [[ "${ID:-}" != "ubuntu" || ! " 24.04 26.04 " =~ " ${VERSION_ID:-} " ]]; then
  echo "Warning: ${PRETTY_NAME:-this system} is not a Supported platform (Ubuntu 24.04 or 26.04)." >&2
fi

echo "==> Installing system packages"
sudo apt-get update
sudo apt-get install --yes --no-install-recommends "${packages[@]}"

restrict=/proc/sys/kernel/apparmor_restrict_unprivileged_userns
if [[ -r "$restrict" && "$(cat "$restrict")" == "1" ]]; then
  profile_path="/etc/apparmor.d/$profile_name"
  echo "==> Installing AppArmor profile $profile_path for $electron_path"
  print_profile | sudo tee "$profile_path" > /dev/null
  sudo apparmor_parser --replace "$profile_path"
else
  echo "==> AppArmor does not restrict user namespaces; no sandbox profile needed"
fi

echo
echo "Done. Next:"
echo "  npm install"
echo "  npm run doctor"
