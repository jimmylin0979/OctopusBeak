export function electronExecutablePath(projectRoot) {
  return resolve(projectRoot, "node_modules", "electron", "dist", "electron");
}

/** One profile per Electron executable path, so two checkouts never share a name. */
export function electronSandboxProfileName(electronPath) {
  const digest = createHash("sha256").update(electronPath).digest("hex").slice(0, 12);
  return `octopusbeak-dev-${digest}`;
}

export function electronSandboxProfile(electronPath) {
  const name = electronSandboxProfileName(electronPath);
  return [
    "# Generated by OctopusBeak (ADR 0138). Lets Electron use its user-namespace sandbox.",
    "abi <abi/4.0>,",
    "include <tunables/global>",
    "",
    `profile ${name} "${electronPath}" flags=(unconfined) {`,
    "  userns,",
    "",
    `  include if exists <local/${name}>`,
    "}",
    "",
  ].join("\n");
}

/** Parses /etc/os-release into its KEY=value pairs. */
export function parseOsRelease(text) {
  const fields = {};
  for (const line of text.split("\n")) {
    const match = /^([A-Z0-9_]+)=(.*)$/u.exec(line.trim());
    if (!match) continue;
    fields[match[1]] = match[2].replace(/^"(.*)"$/u, "$1");
  }
  return fields;
}

export function toolchainVersions(toolVersionsText, packageJson) {
  const node = /^nodejs\s+(\S+)/mu.exec(toolVersionsText)?.[1] ?? null;
  const npm = /^npm@(\S+)$/u.exec(packageJson.packageManager ?? "")?.[1] ?? null;
  return { node, npm };
}

const NODE_FIX = (version) => [
  `Install Node ${version} with a version manager, then run npm install again:`,
  `  mise install    # reads .tool-versions`,
  `  # or: nvm install ${version} && nvm use ${version}`,
];

/**
 * Turns what the host reports into findings. Each finding is
 * { id, status: "ok" | "warn" | "fail" | "skip", summary, fix: string[] }.
 * The probe is plain data so the rules can be checked without a real host.
 */
export function ubuntuEnvironmentFindings(probe) {
  const findings = [];
  const add = (id, status, summary, fix = []) => findings.push({ id, status, summary, fix });

  const os = probe.osRelease;
  if (os.ID === "ubuntu" && SUPPORTED_UBUNTU_VERSIONS.includes(os.VERSION_ID)) {
    add("os", "ok", `Ubuntu ${os.VERSION_ID}`);
  } else {
    add("os", "warn", `${os.PRETTY_NAME ?? "Unknown Linux"} is not a Supported platform`, [
      `OctopusBeak is verified on Ubuntu ${SUPPORTED_UBUNTU_VERSIONS.join(" and ")} only; other systems may work but are not checked.`,
    ]);
  }
  if (probe.arch === SUPPORTED_UBUNTU_ARCH) add("arch", "ok", `CPU architecture ${probe.arch}`);
  else add("arch", "warn", `CPU architecture ${probe.arch} is not a Supported platform`, [`Only ${SUPPORTED_UBUNTU_ARCH} is verified on Ubuntu.`]);

  const expected = probe.toolchain;
  if (probe.nodeVersion === expected.node) add("node", "ok", `Node ${probe.nodeVersion}`);
  else add("node", "fail", `Node ${probe.nodeVersion}, but this repository uses Node ${expected.node}`, NODE_FIX(expected.node));

  if (probe.npmVersion === null) {
    add("npm", "fail", "npm was not found", NODE_FIX(expected.node));
  } else if (probe.npmVersion === expected.npm) {
    add("npm", "ok", `npm ${probe.npmVersion}`);
  } else {
    add("npm", "fail", `npm ${probe.npmVersion}, but this repository uses npm ${expected.npm}`, [
      `npm install --global npm@${expected.npm}`,
    ]);
  }

  if (probe.missingPackages.length === 0) {
    add("packages", "ok", "System libraries and Secret Service packages are installed");
  } else {
    add("packages", "fail", `Missing system packages: ${probe.missingPackages.join(", ")}`, [
      "bash scripts/setup-ubuntu.sh",
    ]);
  }

  if (!probe.userNamespacesRestricted) {
    add("sandbox-profile", "ok", "AppArmor does not restrict user namespaces; no profile is needed");
  } else if (probe.installedProfile === probe.expectedProfile) {
    add("sandbox-profile", "ok", `AppArmor profile ${probe.profileName} allows Electron's sandbox`);
  } else {
    const summary = probe.installedProfile === null
      ? `AppArmor blocks Electron's sandbox and ${probe.profilePath} is missing`
      : `${probe.profilePath} does not match this checkout's Electron path`;
    add("sandbox-profile", "fail", summary, ["bash scripts/setup-ubuntu.sh"]);
  }

  const electron = probe.electron;
  if (electron.status === "skipped") {
    add("electron", "skip", `Electron startup not checked: ${electron.reason}`, electron.fix ?? []);
  } else if (electron.status === "failed") {
    add("electron", "fail", `Electron could not start a sandboxed window: ${electron.reason}`, [
      "Fix the failures above first, then run npm run doctor again.",
    ]);
  } else {
    add("electron", "ok", "Electron starts a sandboxed window");
    if (electron.encryptionAvailable && electron.backend !== "basic_text") {
      add("keyring", "ok", `Credentials are encrypted through ${electron.backend}`);
    } else {
      add("keyring", "fail", `No usable keyring (Electron selected ${electron.backend ?? "none"}); the App will refuse to store sign-in details`, [
        "Install the keyring with bash scripts/setup-ubuntu.sh, then sign out and back in so it unlocks with your session.",
        "On a desktop other than GNOME or KDE, tell Electron to use it: npm run desktop:dev -- --password-store=gnome-libsecret",
      ]);
    }
  }
  return findings;
}
