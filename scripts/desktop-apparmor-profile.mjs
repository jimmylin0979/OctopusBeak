import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";

/**
 * Build the AppArmor profile that lets one checkout's Electron executable use
 * Chromium's user-namespace sandbox on Ubuntu 24.04+. The profile is scoped to
 * that exact path and otherwise leaves the process unconfined.
 */
export function apparmorProfileFor(electronPath) {
  if (!electronPath.startsWith("/")) throw new Error(`Electron path must be absolute: ${electronPath}`);
  // Quotes, backslashes, control characters, and AppArmor globs would change what the rule matches.
  if (/["\\*?[\]{}^\u0000-\u001f]/u.test(electronPath)) {
    throw new Error(`Electron path has characters that are unsafe in an AppArmor rule: ${JSON.stringify(electronPath)}`);
  }
  const name = `octopusbeak-dev-${createHash("sha256").update(electronPath).digest("hex").slice(0, 12)}`;
  const text = [
    "# Generated by scripts/desktop-apparmor-profile.mjs. Lets this checkout's Electron use its user-namespace sandbox.",
    "abi <abi/4.0>,",
    "include <tunables/global>",
    "",
    `profile ${name} "${electronPath}" flags=(unconfined) {`,
    "  userns,",
    "",
    `  include if exists <local/${name}>`,
    "}",
    "",
  ].join("\n");
  return {
    name,
    text,
    commands: [
      `sudo tee /etc/apparmor.d/${name} >/dev/null <<'EOF'\n${text}EOF`,
      `sudo apparmor_parser -r /etc/apparmor.d/${name}`,
    ],
  };
}

function printInstructions() {
  const electron = createRequire(import.meta.url)("electron");
  const restriction = (() => {
    try {
      return readFileSync("/proc/sys/kernel/apparmor_restrict_unprivileged_userns", "utf8").trim();
    } catch {
      return null;
    }
  })();
  if (restriction !== "1") {
    console.log("This system does not restrict unprivileged user namespaces; no AppArmor profile is needed.");
    return;
  }
  const profile = apparmorProfileFor(electron);
  console.log(`Run these once to let this checkout's Electron use its sandbox (${profile.name}):\n`);
  console.log(profile.commands.join("\n"));
  console.log(
    "\nThe profile trusts that exact executable path. Remove it when the checkout is deleted:\n" +
      `  sudo apparmor_parser -R /etc/apparmor.d/${profile.name} && sudo rm /etc/apparmor.d/${profile.name}\n` +
      "List registered checkouts with: ls /etc/apparmor.d | grep '^octopusbeak-dev-'",
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) printInstructions();
